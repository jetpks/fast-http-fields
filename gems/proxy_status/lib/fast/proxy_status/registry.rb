    class << self
      # Is +name+ one of §2.3's 32 proxy error types? An unknown name
      # answers false, and passes through the field untouched either way.
      def registered?(name)
        ERRORS.key?(name)
      end

      # §2.3's Recommended HTTP Status Code for +name+ — an Integer, or
      # the RFC's own prose for the two entries whose recommendation is
      # not a number (http_request_error, proxy_internal_response) — or
      # nil for a name the registry does not carry. Advisory: §2.1.1
      # makes it a SHOULD for the sender, never a bound enforced here.
      def recommended_status(name)
        entry = ERRORS[name]
        entry && entry["recommended_status"]
      end

      # §2.3's "Response Only Generated by Intermediaries" flag for
      # +name+ — false for an unknown name: a type the registry does not
      # carry is not known to be response-only.
      def response_only?(name)
        entry = ERRORS[name]
        entry ? entry["response_only"] : false
      end

      # §2.3's Extra Parameters table for +name+ — a frozen Hash of
      # name => Structured Type, {} where the entry says "None" — or nil
      # for an unknown name. Advisory data: a parameter used with a type
      # it is not defined for "will be ignored" (§2.1.1), so the table
      # never gates anything.
      def extra_parameters(name)
        entry = ERRORS[name]
        entry && entry["extra_parameters"]
      end
    end
