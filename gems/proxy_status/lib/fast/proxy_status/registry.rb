    # RFC 9209 §2.3 — the 32 proxy error types this document defines,
    # pinned as frozen data in document order. A gem that pins its RFC's
    # registry at publication passes unknown values through, so a future
    # registration never breaks an old gem version. Each entry is a
    # frozen Hash of the three fields the registry's template names:
    # "recommended_status" (an Integer — two entries carry the RFC's own
    # prose instead: http_request_error's "The applicable 4xx status
    # code" and proxy_internal_response's "The most appropriate status
    # code for the response"), "response_only" (§2.1.1: "Proxy error
    # types that are registered with a 'Response only generated by
    # intermediaries' value of 'true' indicate that they can only occur
    # in responses generated by the intermediary. If the value is
    # 'false', the response might be generated by the intermediary or an
    # inbound server.") and "extra_parameters" (the name => Structured
    # Type table the entry defines — §2.1.1: "Their use, like all
    # parameters, is optional. As a result, if an extra parameter is used
    # with a proxy error type for which it is not defined, it will be
    # ignored.").
    #
    # The registry is ADVISORY data and never gates a parse or an emit:
    # an error type it does not carry parses, emits and round-trips
    # untouched, and recommended_status is the status code a sender
    # SHOULD set ("When generating an HTTP response containing the error,
    # its HTTP status code SHOULD be set to the recommended HTTP status
    # code"), never a bound the library enforces.
